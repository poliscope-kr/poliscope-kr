export const areaWords = area => {
  if (/비례/.test(area)) return [];
  const last = String(area).trim().split(/\s+/).pop();
  return [...last.matchAll(/([가-힣]+?)(?:특별자치시|특별시|광역시|시|군|구)/g)].map(x => x[1]).filter(w => w.length >= 2);
};
